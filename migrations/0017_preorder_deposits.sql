CREATE TABLE IF NOT EXISTS preorder_deposits (
  id TEXT PRIMARY KEY,
  number INTEGER NOT NULL UNIQUE,
  product_id TEXT NOT NULL REFERENCES products(id),
  variant_id TEXT NOT NULL REFERENCES variants(id),
  product_title TEXT NOT NULL,
  variant_title TEXT NOT NULL,
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  phone TEXT NOT NULL,
  address TEXT NOT NULL,
  city TEXT NOT NULL,
  shipping_code TEXT NOT NULL,
  shipping_label TEXT NOT NULL,
  price INTEGER NOT NULL CHECK (price >= 0),
  shipping INTEGER NOT NULL CHECK (shipping >= 0),
  deposit INTEGER NOT NULL CHECK (deposit > 0 AND deposit <= price),
  balance INTEGER NOT NULL CHECK (balance = price - deposit + shipping),
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'paid', 'shipped', 'cancelled')),
  provider_order_id TEXT UNIQUE,
  provider_txn TEXT,
  checkout_url TEXT,
  expires_at INTEGER NOT NULL,
  paid_at INTEGER,
  notified_at INTEGER,
  notify_attempts INTEGER NOT NULL DEFAULT 0,
  created_at INTEGER NOT NULL DEFAULT (unixepoch())
);
CREATE INDEX IF NOT EXISTS preorder_deposits_status ON preorder_deposits(status, created_at DESC)
